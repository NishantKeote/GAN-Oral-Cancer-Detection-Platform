"""Complete response schema for POST /analyze endpoint."""

from typing import Any, Dict, List
from pydantic import BaseModel, Field
from app.schemas.case import PatientContext
from app.schemas.graph import GraphNodeContext
from app.schemas.rag import LiteratureEvidenceChunk
from app.schemas.report import GroqReport
from app.schemas.xai import XAISummary


class AnalysisResponse(BaseModel):
    """Unified multimodal response returned by POST /analyze."""

    case_id: str = Field(..., description="Unique case identifier (e.g. CASE-XXXXXXXXXX)")
    filename: str = Field(..., description="Original filename of the uploaded image")
    patient_context: PatientContext = Field(..., description="Supplied and normalized clinical metadata")
    research_question: str = Field(default="", description="Guiding research question")
    prediction: str = Field(..., description="Predicted diagnostic class ('OSCC' or 'Normal')")
    class_index: int = Field(..., description="Predicted class index (0 for Normal, 1 for OSCC)")
    oscc_probability: float = Field(..., description="Continuous sigmoid score from EfficientNetB0")
    threshold: float = Field(..., description="Classification threshold applied")
    decision_rule: str = Field(..., description="Explicit rule used to assign the class label")
    confidence: float = Field(..., description="Probability of predicted class")
    confidence_percent: float = Field(..., description="Confidence expressed as a percentage [0-100]")
    xai: XAISummary = Field(..., description="Explainable AI attributions, overlays, and metrics")
    graph_saved: bool = Field(..., description="Whether the case was successfully persisted in Neo4j")
    graph_context: List[GraphNodeContext] = Field(
        default_factory=list,
        description="Relevant disease relationships retrieved from Neo4j",
    )
    retrieval_query: str = Field(..., description="Dynamic query constructed for RAG search")
    literature_evidence: List[LiteratureEvidenceChunk] = Field(
        default_factory=list,
        description="Top-k matching scientific literature chunks from FAISS",
    )
    errors: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="Non-fatal degradation errors encountered during processing",
    )
    scope_note: str = Field(
        ...,
        description="Standardized scientific research and clinical limitation disclaimer",
    )
    report: GroqReport = Field(..., description="Grounded research report generated by Groq")
